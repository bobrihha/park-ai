from core.utils import get_prices_from_knowledge, get_prices_text

def get_system_prompt(intent: str, park_id: str = "nn") -> str:
    """
    Получить системный промпт в зависимости от намерения.
    Сначала пытается загрузить из БД, при отсутствии — использует код.
    """
    
    prices = get_prices_from_knowledge()
    prices_text = get_prices_text()
    
    # Динамические цены
    prices_block = f"""
ЦЕНЫ НА БИЛЕТЫ:
- Пн: {prices['monday']}₽
- Вт-Пт: {prices['weekday']}₽
- Вых/праздники: {prices['weekend']}₽
- Взрослые: БЕСПЛАТНО
- До 1 года: БЕСПЛАТНО

{prices_text}
"""
    
    # Пытаемся загрузить промпты из БД
    try:
        from db import SessionLocal, Prompt
        db = SessionLocal()
        
        # Загружаем базовый промпт
        base_prompt = db.query(Prompt).filter(
            Prompt.park_id == park_id,
            Prompt.intent == "base",
            Prompt.is_active == True
        ).first()
        
        # Загружаем промпт для конкретного intent
        intent_prompt = db.query(Prompt).filter(
            Prompt.park_id == park_id,
            Prompt.intent == intent,
            Prompt.is_active == True
        ).first()
        
        db.close()
        
        # Если промпты найдены в БД — используем их
        if base_prompt:
            base_content = base_prompt.content + prices_block
            if intent_prompt:
                return base_content + intent_prompt.content
            else:
                # Fallback на код для intent, если не нашли в БД
                if intent == "birthday":
                    return base_content + BIRTHDAY_PROMPT
                elif intent == "general":
                    return base_content + GENERAL_PROMPT
                elif intent == "events":
                    return base_content + EVENTS_PROMPT
                else:
                    return base_content + CLARIFICATION_PROMPT
                    
    except Exception as e:
        # При ошибке импорта БД или других проблемах — используем код
        import logging
        logging.getLogger(__name__).warning(f"Failed to load prompts from DB: {e}. Using code fallback.")
    
    # Fallback: используем промпты из кода
    base = BASE_SYSTEM_PROMPT + prices_block
    
    if intent == "birthday":
        return base + BIRTHDAY_PROMPT
    elif intent == "general":
        return base + GENERAL_PROMPT
    elif intent == "events":
        return base + EVENTS_PROMPT
    else:
        return base + CLARIFICATION_PROMPT
